"""Generate docs/algorithm_comparison.md and docs/worked_examples.md.

Every number in those two files comes from this script (leakcalc.compare and
tests/examples.py); do not edit the generated files by hand.

Run:  python -I -B tools/make_docs.py
"""

import sys
from pathlib import Path


def _write(path, text):
    """UTF-8 with LF line endings (works on Python 3.9; Path.write_text(newline=) needs 3.10)."""
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

from leakcalc import __version__, compare  # noqa: E402
from examples import EXAMPLES, within  # noqa: E402

HEADER = "<!-- Generated by tools/make_docs.py from leakcalc {v}. Do not edit by hand. -->\n\n"


def fmt(x, nd=0):
    return f"{x:,.{nd}f}"


def comparison():
    ref = compare.REFERENCE
    rows = compare.run()
    ratio, lo, hi = compare.spread(rows, "core")
    core = [r for r in rows if r["group"] == "core"]
    no_lf = [r for r in core if "load factor 0.6" not in r["method"]]
    r2, lo2, hi2 = (max(x["kwh_per_year"] for x in no_lf) / min(x["kwh_per_year"] for x in no_lf),
                    min(x["kwh_per_year"] for x in no_lf), max(x["kwh_per_year"] for x in no_lf))
    fmin, fmax = min(x["flow_scfm"] for x in core), max(x["flow_scfm"] for x in core)
    fspread = fmax / fmin
    rall, loall, hiall = compare.spread([r for r in rows if r["group"] in ("core", "control")])
    out = [HEADER.format(v=__version__), "# One leak, many published methods\n",
           f"Reference case: a {ref['diameter_in']:.3f}-in (1/8-in) hole at {ref['line_psig']} psig that leaks for "
           f"{ref['hours']:,} h/yr. Each method uses its own published defaults. Inputs that the leak does not fix "
           f"are shared: air temperature {ref['air_temp_f']:g} F at the compressor inlet and at the leak, motor "
           f"efficiency {ref['motor_eff']:.2f}, a single-stage rotary-screw compressor, and {ref['kw_per_cfm']} kW per cfm "
           "where a method needs a specific power. Atmospheric pressure is 14.7 psia throughout. Flow is volume "
           "of free air at 14.7 psia, as each source defines it: Essentials at compressor-inlet temperature, the Tip "
           "Sheet as tabulated, and the Workbook mass flow divided by 0.07494 lbm/ft3 (air at 70 F).\n",
           "## 1. Methods as published, without a control-mode correction\n",
           "| Method | Source | Flow (cfm) | Savings (kWh/yr) | Ratio to lowest |", "|---|---|---:|---:|---:|"]
    for r in sorted(core, key=lambda x: x["kwh_per_year"]):
        out.append(f"| {r['method']} | {r['source']} | {fmt(r['flow_scfm'], 2)} | {fmt(r['kwh_per_year'])} | "
                   f"{r['kwh_per_year'] / lo:.2f} |")
    out += ["", f"**Spread: {fmt(lo)} to {fmt(hi)} kWh/yr, a factor of {ratio:.2f}.**\n",
            "Where the spread comes from:\n",
            f"- The low end is the Self-Assessment Workbook with its worked example's average partial-load factor "
            f"of 0.6. That factor is a plant-specific assumption in the example, not part of Fliegner's formula. "
            f"Without that row the spread is {fmt(lo2)} to {fmt(hi2)} kWh/yr, a factor of {r2:.2f}.",
            "- The high end is the Tip Sheet table with the well-rounded orifice factor 0.97. The sharp-orifice "
            f"factor 0.61 used in the Tip Sheet's own example gives {100 * (1 - 0.61 / 0.97):.0f} % less for the same hole.",
            f"- Flow estimates alone differ by a factor of {fspread:.2f} (lowest {fmt(fmin, 2)}, highest {fmt(fmax, 2)} cfm); "
            "the rest comes from how each method converts flow to electricity (specific power, compressor and "
            "motor efficiency, isothermal vs. adiabatic compression).\n",
            "Assumptions behind each row:\n"]
    for r in sorted(core, key=lambda x: x["kwh_per_year"]):
        out.append(f"- {r['method']}: {r['assumptions']}.")
    ref_rows = [r for r in rows if r["group"] == "reference"]
    if ref_rows:
        out += ["", "For reference only (not a published choice; the Tip Sheet says the table values should be "
                    "multiplied by 0.97 or 0.61):", ""]
        for r in ref_rows:
            out.append(f"- {r['method']}: {fmt(r['flow_scfm'], 2)} cfm, {fmt(r['kwh_per_year'])} kWh/yr.")
    out += ["", "## 2. With the published control-mode corrections\n",
            "UMP Chapter 22 multiplies by a trim-compressor control adjustment factor (CCAF, Table 5). Schmidt & "
            "Kissock (2004, 2005) multiply the full-load saving by (1 - FP0), the slope of their linear part-load "
            "model; FP0 values below are read from their Figure 2 (2005) to the nearest 5 %.\n",
            "| Method | Flow (cfm) | Savings (kWh/yr) |", "|---|---:|---:|"]
    for r in [r for r in rows if r["group"] == "control"]:
        out.append(f"| {r['method']} | {fmt(r['flow_scfm'], 2)} | {fmt(r['kwh_per_year'])} |")
    out += ["", f"Across sections 1 and 2 together the estimates run from {fmt(loall)} to {fmt(hiall)} kWh/yr, "
                f"a factor of {rall:.2f}. Control mode alone moves the UMP estimate by a factor of "
                f"{1.0 / 0.30:.2f} (CCAF 1.00 vs 0.30).\n",
            "## 3. Caveats\n",
            "- This is a scenario comparison using alternative published assumptions, not a controlled test of the "
            "methods: besides the equations, the rows differ in orifice factor, load factor, compressor and control "
            "type, and compression model, as listed under each table. Real assessments also differ in the hole size "
            "someone estimates by ear, the hours, and the pressure, which this table does not cover.",
            "- The Essentials row depends on the assumed motor efficiency (0.90 here). Its own worked example "
            "uses 0.915 but its results table appears to omit the motor efficiency (see worked_examples.md, ESS-2).",
            "- UMP's simplified Equation 12 is valid only for a single trim compressor whose count of running units "
            "does not change, in a system that 'is well-controlled and operates predictably' (UMP p. 18); otherwise "
            "UMP requires a CFM-bin analysis, which is not implemented. Each CCAF is the slope of the part-load curve "
            "between 40 % and 80 % capacity (UMP p. 19).",
            "- All numbers here are computed by `tools/make_docs.py`; `tests/test_behaviour.py` pins the "
            "low and high values of section 1.\n"]
    return "\n".join(out)


def worked():
    out = [HEADER.format(v=__version__), "# Worked examples from the sources\n",
           "Each printed example is recomputed with leakcalc (tests/examples.py, run by "
           "tests/test_worked_examples.py). 'Reproduced' means equal within the rounding of the printed value. "
           "Where a printed value cannot be reproduced from the source's own equation, the row says so and "
           "gives the possible causes, separating what the source shows from what is inferred; the equations were not "
           "changed to force agreement. The rows are 33 test cases from six documents (five method modules); some "
           "are diagnostic variants of the same printed value (ESS-2b, WB-1b, SK04-3b, SK04-4b, SK05-3b).\n",
           "| ID | Source, page | What | Printed | Recomputed | Result |", "|---|---|---|---:|---:|---|"]
    n_ok = 0
    for e in EXAMPLES:
        v = e["value"]()
        ok = within(v, e["printed"], e["rtol"])
        n_ok += ok
        res = "reproduced" if ok else "**does not match**"
        if ok != e["match"]:
            res += " (UNEXPECTED - see test output)"
        out.append(f"| {e['id']} | {e['source']}, {e['page']} | {e['what']} | {e['printed']:,.6g} | {v:,.6g} | {res} |")
    out += ["", f"{n_ok} of {len(EXAMPLES)} rows reproduce the printed value; {len(EXAMPLES) - n_ok} do not.\n",
            "## Notes\n"]
    for e in EXAMPLES:
        if e["note"]:
            out.append(f"- **{e['id']}**: {e['note']}")
    return "\n".join(out) + "\n"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    (ROOT / "docs").mkdir(exist_ok=True)
    _write(ROOT / "docs" / "algorithm_comparison.md", comparison())
    _write(ROOT / "docs" / "worked_examples.md", worked())
    print("wrote docs/algorithm_comparison.md and docs/worked_examples.md")


if __name__ == "__main__":
    main()
